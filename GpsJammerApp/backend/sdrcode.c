extern short *gencode(int prn, int ctype, int *len, double *crate) {
    switch (ctype) {
    case CTYPE_L1CA:
        return gencode_L1CA(prn, len, crate);
    case CTYPE_L1CP:
        return boc(gencode_L1CP(prn, len, crate), len, crate, 1, 1);
    case CTYPE_L1CD:
        return boc(gencode_L1CD(prn, len, crate), len, crate, 1, 1);
    case CTYPE_L1CO:
        return gencode_L1CO(prn, len, crate);
    case CTYPE_L1SBAS:
        return gencode_L1CA(prn, len, crate);
    case CTYPE_E1B:
        return boc(gencode_E1B(prn, len, crate), len, crate, 1, 1);
    case CTYPE_G1:
        return gencode_G1G2(len, crate);
    case CTYPE_NH10:
        return gencode_NH10(len, crate);
    case CTYPE_NH20:
        return gencode_NH20(len, crate);
    default:
        SDRPRINTF("error: gencode prn:%d ctype:%d", prn, ctype);
        return NULL;
    }
}
