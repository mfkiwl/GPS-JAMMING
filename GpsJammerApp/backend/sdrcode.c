void fliparrays(short *in, int n, short *out) {
    int i;
    short *tmp;
    tmp = (short *)malloc(n * sizeof(short));
    if (tmp != NULL) {
        memcpy(tmp, in, n);
        for (i = 0; i < n; i++)
            out[n - i - 1] = tmp[i];
        free(tmp);
    }
}

